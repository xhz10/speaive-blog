#!/usr/bin/env python3
"""Validate the curated corpus and generate a repeatable PostgreSQL seed; never connect to a database."""
import argparse
import json
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
MECHANISMS = {'LITERAL', 'CAUSAL_REVERSAL', 'CONCEPT_MISMATCH', 'DAILY_LIFE', 'PERSONIFICATION'}
SOURCES = {'PRIMARY_LISTING', 'PRIMARY_POST', 'REPRINT'}
ROLES = [
    ('fda22f13-deb5-5477-a7f9-ab8fc5c00995', 'rz_wang_laoshi', 'LITERAL'),
    ('44a577e9-406a-54db-9601-a8cac7b2aa34', 'rz_yinguo_daoye', 'CAUSAL_REVERSAL'),
    ('cb7ba866-9f2f-58bb-aad6-13a7238d8300', 'rz_qinglong_researcher', 'CONCEPT_MISMATCH'),
    ('952d560b-0149-5163-ae28-80d68ecccd88', 'rz_moyu_shifu', 'DAILY_LIFE'),
    ('da9dbf77-6035-5cd5-96d0-862c3f239954', 'rz_moon_service', 'PERSONIFICATION'),
]


def quote(value):
    return "'" + str(value).replace("'", "''") + "'"


def build(corpus):
    items = corpus if isinstance(corpus, list) else corpus['items']
    ids = set()
    for item in items:
        for field, maximum in [('id', 80), ('excerpt', 500), ('sourceUrl', 2048),
                               ('sourceTitle', 200), ('analysis', 1200), ('adaptation', 1200)]:
            value = item[field]
            if not isinstance(value, str) or '\0' in value or value != value.strip() or not 0 < len(value) <= maximum:
                raise ValueError(f'{item.get("id")}: invalid {field}')
        if item['id'] in ids:
            raise ValueError(f'duplicate id: {item["id"]}')
        ids.add(item['id'])
        source = urlparse(item['sourceUrl'])
        if source.scheme not in {'https', 'http'} or not source.hostname or source.username:
            raise ValueError(f'{item["id"]}: invalid source URL')
        if item['mechanism'] not in MECHANISMS or item['sourceKind'] not in SOURCES:
            raise ValueError(f'{item["id"]}: invalid classification')
        topics = item['topics']
        if not 1 <= len(topics) <= 12 or len(set(topics)) != len(topics):
            raise ValueError(f'{item["id"]}: invalid topics')
        if any(not isinstance(topic, str) or '\0' in topic or topic != topic.strip()
               or not 0 < len(topic) <= 50 for topic in topics):
            raise ValueError(f'{item["id"]}: invalid topic')
        if type(item['quality']) is not int or not 1 <= item['quality'] <= 5:
            raise ValueError(f'{item["id"]}: invalid quality')
    if not items:
        raise ValueError('corpus is empty')

    lines = [
        '-- Generated by scripts/build-ruozhi-seed.py from docs/knowledge/ruozhi-corpus.json.',
        '-- PostgreSQL: first complete Flyway V14, then execute seed-ruozhi-agents.sql.',
        '-- Repeat execution preserves all existing material edits, enablement and role bindings.',
        '-- docker compose exec -T postgres sh -ec \'exec psql --username="$POSTGRES_USER" --dbname="$POSTGRES_DB" --set=ON_ERROR_STOP=1\' < scripts/sql/seed-ruozhi-knowledge.sql',
        'BEGIN;', 'SET LOCAL standard_conforming_strings = on;', "SET LOCAL lock_timeout = '10s';",
        'SELECT pg_advisory_xact_lock(1936747621, 20261012);',
        'DO $preflight$ BEGIN',
        "IF to_regclass('public.blog_humor_material') IS NULL THEN",
        "RAISE EXCEPTION '请先完成 Flyway V14 数据库迁移。'; END IF;",
    ]
    for agent_id, username, _ in ROLES:
        lines += [
            'IF NOT EXISTS (SELECT 1 FROM public.blog_user u JOIN public.blog_agent a ON a.id = u.id',
            f'WHERE u.id = {quote(agent_id)} AND u.username = {quote(username)}',
            "AND u.type = 'AGENT' AND a.owner_account_id IS NULL) THEN",
            f"RAISE EXCEPTION '缺少站长角色 {username}，请先执行 seed-ruozhi-agents.sql。'; END IF;",
        ]
    lines += ['END; $preflight$;',
              'INSERT INTO public.blog_humor_material (id, excerpt, source_url, source_title, source_kind, topics, mechanism, analysis, adaptation, quality, enabled, version, created_at, updated_at) VALUES']
    values = []
    for item in items:
        fields = [quote(item[field]) for field in ['id', 'excerpt', 'sourceUrl', 'sourceTitle', 'sourceKind']]
        fields += ['ARRAY[' + ', '.join(quote(topic) for topic in item['topics']) + ']::TEXT[]']
        fields += [quote(item[field]) for field in ['mechanism', 'analysis', 'adaptation']]
        fields += [str(item['quality']), 'TRUE', '1', 'CURRENT_TIMESTAMP', 'CURRENT_TIMESTAMP']
        values.append('(' + ', '.join(fields) + ')')
    lines += [',\n'.join(values), 'ON CONFLICT (id) DO NOTHING;',
              'INSERT INTO public.blog_agent_humor_profile (agent_id, mechanism, enabled) VALUES',
              ',\n'.join(f'({quote(agent_id)}, {quote(mechanism)}, TRUE)' for agent_id, _, mechanism in ROLES),
              'ON CONFLICT (agent_id) DO NOTHING;',
              'SELECT mechanism, COUNT(*) AS material_count FROM public.blog_humor_material GROUP BY mechanism ORDER BY mechanism;',
              'SELECT agent_id, mechanism, enabled FROM public.blog_agent_humor_profile ORDER BY mechanism;', 'COMMIT;', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check that generated SQL is current without writing')
    options = parser.parse_args()
    corpus_path = ROOT / 'docs/knowledge/ruozhi-corpus.json'
    destination = ROOT / 'scripts/sql/seed-ruozhi-knowledge.sql'
    sql = build(json.loads(corpus_path.read_text(encoding='utf-8')))
    if options.check:
        if not destination.exists() or destination.read_text(encoding='utf-8') != sql:
            raise SystemExit('Generated SQL is outdated; run python3 scripts/build-ruozhi-seed.py')
        print('Corpus validation and generated SQL consistency passed.')
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(sql, encoding='utf-8')
        print(f'Generated {destination}')
